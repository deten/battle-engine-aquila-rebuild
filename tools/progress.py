"""Regenerate docs/PROGRESS.md from the BEA_HOOK registrations under src/.

Usage: python -I tools/progress.py
"""
import csv, os, re, glob, collections, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME_LO, GAME_HI = 0x401000, 0x55A420   # game code range from docs/INVESTIGATION.md §8

funcs = {}
for r in csv.DictReader(open(os.path.join(ROOT, 'ghidra_out', 'functions.csv'), encoding='utf-8', errors='replace')):
    a = int(r['address'], 16)
    if GAME_LO <= a < GAME_HI and r['is_thunk'] != 'true':
        name = r['name'] if r['namespace'] in ('', 'Global') else r['namespace'] + '::' + r['name']
        funcs[a] = (name, int(r['size']), int(r['callers']))
total = len(funcs)
total_bytes = sum(f[1] for f in funcs.values())

hooks = []  # (addr, fn, file)
pat = re.compile(r'BEA_HOOK(?:_T|_TRIVIAL)?\(\s*(0x[0-9A-Fa-f]+)\s*,\s*([A-Za-z_][A-Za-z0-9_:<>, x]*?)\s*\)')
for path in sorted(glob.glob(os.path.join(ROOT, 'src', '**', '*.cpp'), recursive=True) +
                   glob.glob(os.path.join(ROOT, 'src', '**', '*.inc'), recursive=True)):
    rel = os.path.relpath(path, ROOT).replace('\\', '/')
    text = open(path, encoding='utf-8').read()
    for m in pat.finditer(text):
        hooks.append((int(m.group(1), 16), m.group(2), rel))
    # BEA_PARITY_HOOK(0x0046cdf0, 0046cdf0, ap_0046cdf0, body, table) (bea/parity.h)
    for m in re.finditer(r'BEA_PARITY_HOOK\(\s*(0x[0-9A-Fa-f]+)\s*,\s*\w+\s*,\s*(\w+)', text):
        hooks.append((int(m.group(1), 16), m.group(2), rel))
    # LIFT_FUNCTION[_NF](0x00554750, 00554750): an asm-lifted function (src/bea/lifted, on unless BEA_LIFT=0)
    for m in re.finditer(r'^LIFT_FUNCTION(?:_NF)?\(\s*(0x[0-9A-Fa-f]+)\s*,\s*(\w+)\s*\)', text, re.M):
        hooks.append((int(m.group(1), 16), 'lift_' + m.group(2), rel))

seen = set()
replaced = []
for a, fn, rel in hooks:
    if a in seen:
        raise SystemExit("duplicate hook for %08x (%s)" % (a, fn))
    seen.add(a)
    replaced.append((a, fn, rel))
replaced.sort()

in_game = [r for r in replaced if r[0] in funcs]
bytes_done = sum(funcs[a][1] for a, _, _ in in_game)
def method(rel):
    """How the replacement was produced (see NOTES.md A1-8/A1-10)."""
    if rel.startswith('src/bea/verified/'):
        return 'auto-ported, shadow-verified (src/bea/verified)'
    if rel.startswith('src/bea/direct/'):
        return 'auto-ported, direct (src/bea/direct: static checks + soak only)'
    if rel.startswith('src/bea/lifted/'):
        return 'asm-lifted, verified offline (src/bea/lifted)'
    if rel.endswith('_generated.inc'):
        return 'generated from templates (%s)' % rel
    return 'hand-written'
by_method = collections.Counter(method(rel) for _, _, rel in in_game)
# one row per generated directory, one per hand-written file
by_file = collections.Counter(re.sub(r'^(src/bea/(?:verified|direct|autoport))/ap_[0-9a-f]{8}\.cpp$|^(src/bea/lifted)/lift_[0-9a-f]{8}\.cpp$',
                                     lambda m: (m.group(1) or m.group(2)) + '/ (one file per function)', rel) for _, _, rel in in_game)

out = []
out.append("# PROGRESS.md — Phase 1 function replacement\n")
out.append("Generated by `tools/progress.py` on %s. Do not edit by hand.\n" % datetime.date.today().isoformat())
out.append("| | count | bytes |\n|---|---|---|")
out.append("| game functions (0x%X–0x%X, non-thunk) | %d | %d |" % (GAME_LO, GAME_HI, total, total_bytes))
out.append("| replaced | **%d** | %d |" % (len(in_game), bytes_done))
out.append("| remaining | %d | %d |" % (total - len(in_game), total_bytes - bytes_done))
out.append("| progress | **%.2f %%** of functions | %.2f %% of bytes |\n" % (100.0 * len(in_game) / total, 100.0 * bytes_done / total_bytes))
other = [r for r in replaced if r[0] not in funcs]
if other:
    out.append("%d additional hooks target addresses outside the game range (library code).\n" % len(other))
out.append("## By method\n")
out.append("| method | functions |\n|---|---|")
for m_, n in by_method.most_common():
    out.append("| %s | %d |" % (m_, n))
out.append("\n## By source file\n")
out.append("| file | functions |\n|---|---|")
for rel, n in sorted(by_file.items()):
    out.append("| `%s` | %d |" % (rel, n))
out.append("\n## Replaced functions\n")
out.append("| address | Ghidra name | size | callers | replacement | file |\n|---|---|---|---|---|---|")
for a, fn, rel in replaced:
    g = funcs.get(a, ('(outside game range)', 0, 0))
    out.append("| 0x%08x | `%s` | %d | %d | `%s` | `%s` |" % (a, g[0], g[1], g[2], fn, rel))
open(os.path.join(ROOT, 'docs', 'PROGRESS.md'), 'w', encoding='utf-8').write("\n".join(out) + "\n")
print("replaced %d / %d game functions (%.2f%%), %d / %d bytes" % (len(in_game), total, 100.0 * len(in_game) / total, bytes_done, total_bytes))
